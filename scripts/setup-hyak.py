#!/usr/bin/env python3
"""Set up SSH + SkyPilot Slurm config for Hyak (klone, tillicum).

Run inside the pixi env (needs skypilot installed):
    pixi run setup-hyak --uwnetid <uwnetid>

1. ~/.slurm/config: tells SkyPilot which Slurm clusters exist (adds klone/tillicum
   entries if missing, never edits existing ones).
2. ~/.ssh/hyak.conf (+ Include in ~/.ssh/config): makes `ssh klone-login` /
   `ssh tillicum-login` share their Duo MFA login with SkyPilot.

Hyak requires Duo MFA, which SkyPilot's background polling can't answer, so every
SkyPilot SSH connection without an authenticated master is a failed login (enough
of those and Hyak blocks you). SkyPilot always uses its own ControlPath for Slurm
login nodes and it's not configurable:
    /tmp/sky_ssh_<user_hash>/<md5('__default__')[:10]>/%C
so we point our own login aliases at that same socket instead.
"""

import argparse
import hashlib
import shutil
import sys
from datetime import datetime
from pathlib import Path

from sky.utils import command_runner

SSH_DIR = Path.home() / ".ssh"
SSH_CONFIG = SSH_DIR / "config"
HYAK_CONFIG = SSH_DIR / "hyak.conf"
SLURM_CONFIG = Path.home() / ".slurm" / "config"
INCLUDE_LINE = "Include ~/.ssh/hyak.conf"
CLUSTERS = {"klone": "klone.hyak.uw.edu", "tillicum": "tillicum.hyak.uw.edu"}

def parse_args():
    parser = argparse.ArgumentParser(description="Set up ~/.slurm/config and Duo MFA sharing with SkyPilot for Hyak.")
    parser.add_argument("--uwnetid", required=True, help="Your UW NetID (e.g. scottyh)")
    return parser.parse_args()

def backup(path: Path):
    dest = path.with_name(f"{path.name}.bak-{datetime.now():%Y%m%d-%H%M%S}")
    shutil.copy2(path, dest)
    print(f"Backed up {path} -> {dest}")

def config_hosts(path: Path) -> dict[str, int]:
    """Host names defined in an ssh-style config, mapped to their line number."""
    hosts = {}
    for n, line in enumerate(path.read_text().splitlines(), 1):
        words = line.split()
        if len(words) > 1 and words[0].lower() == "host":
            hosts.update({h: n for h in words[1:]})
    return hosts

def setup_slurm_config(uwnetid: str):
    """Add a SkyPilot Slurm cluster entry per Hyak cluster, leaving existing entries alone."""
    existing = config_hosts(SLURM_CONFIG) if SLURM_CONFIG.exists() else {}
    missing = [c for c in CLUSTERS if c not in existing]
    for c in CLUSTERS:
        if c in existing:
            print(f"{SLURM_CONFIG}:{existing[c]} already defines '{c}', leaving it as is")
    if not missing:
        return
    blocks = [
        f"Host {c}\n    HostName {CLUSTERS[c]}\n    User {uwnetid}\n    IdentitiesOnly yes\n"
        for c in missing
    ]
    if SLURM_CONFIG.exists():
        backup(SLURM_CONFIG)
        text = SLURM_CONFIG.read_text().rstrip("\n") + "\n\n"
    else:
        SLURM_CONFIG.parent.mkdir(exist_ok=True)
        text = ""
    SLURM_CONFIG.write_text(text + "\n".join(blocks))
    print(f"Added {', '.join(missing)} to {SLURM_CONFIG}")

def skypilot_control_dir() -> str:
    """Directory SkyPilot uses for Slurm login-node ControlMaster sockets."""
    # Same derivation as SSHCommandRunner.__init__ for ssh_control_name='__default__'
    # (private API, but it means this tracks SkyPilot if the scheme changes)
    name = hashlib.md5(command_runner.DEFAULT_SSH_CONTROL_NAME.encode(),
                       usedforsecurity=False).hexdigest()[:command_runner._HASH_MAX_LENGTH]
    return command_runner._ssh_control_path(name)

def render_ssh_config(uwnetid: str, control_dir: str) -> str:
    hostnames = " ".join(CLUSTERS.values())
    aliases = ",".join(f"{c}-login" for c in CLUSTERS)
    lines = [
        "# Generated by skypilot-hyak/scripts/setup-hyak.py -- rerun it instead of editing.",
        "#",
        "# `ssh klone-login` / `ssh tillicum-login` ask for Duo once and keep the connection",
        "# open for 24h at the socket path SkyPilot uses, so SkyPilot reuses it without MFA.",
        "",
        "# SkyPilot connects by full hostname. Never let it attempt a login itself: each attempt",
        "# is a failed MFA login on Hyak. Without a live connection from the aliases below,",
        "# ssh fails locally (rerun `ssh klone-login` or `ssh tillicum-login` to fix).",
        f"Host {hostnames}",
        "    PubkeyAuthentication no",
        "    KbdInteractiveAuthentication no",
        "    PasswordAuthentication no",
        "    GSSAPIAuthentication no",
        "    BatchMode yes",
        "",
        "# /tmp is cleared on reboot; recreate the socket directory before connecting",
        f'Match host {aliases} exec "mkdir -p {control_dir}"',
    ]
    for cluster, hostname in CLUSTERS.items():
        lines += [
            "",
            f"Host {cluster}-login",
            f"    HostName {hostname}",
            f"    User {uwnetid}",
            "    ForwardAgent yes",
            "    ControlMaster auto",
            f"    ControlPath {control_dir}/%C",
            "    ControlPersist 24h",
        ]
    return "\n".join(lines) + "\n"

def setup_ssh_config(uwnetid: str):
    SSH_DIR.mkdir(mode=0o700, exist_ok=True)
    control_dir = skypilot_control_dir()
    HYAK_CONFIG.write_text(render_ssh_config(uwnetid, control_dir))
    HYAK_CONFIG.chmod(0o600)
    print(f"Wrote {HYAK_CONFIG} (SkyPilot socket dir: {control_dir})")

    # Include goes at the top of ~/.ssh/config: ssh uses the first value it finds
    text = SSH_CONFIG.read_text() if SSH_CONFIG.exists() else ""
    if INCLUDE_LINE not in text.splitlines():
        if text:
            backup(SSH_CONFIG)
        SSH_CONFIG.write_text(f"{INCLUDE_LINE}\n\n{text}")
        SSH_CONFIG.chmod(0o600)
        print(f"Added '{INCLUDE_LINE}' to the top of {SSH_CONFIG}")

    # Older setups defined these hosts directly; those entries are now shadowed
    shadowed = {f"{c}-login" for c in CLUSTERS} | set(CLUSTERS.values())
    for host, n in config_hosts(SSH_CONFIG).items():
        if host in shadowed:
            print(f"  WARNING: {SSH_CONFIG}:{n} defines '{host}', now overridden by hyak.conf; remove that block")

def main():
    args = parse_args()
    setup_slurm_config(args.uwnetid)
    setup_ssh_config(args.uwnetid)
    print("\nNext: `ssh klone-login` and/or `ssh tillicum-login` (Duo once per 24h), then use `sky` as normal.")

if __name__ == "__main__":
    sys.exit(main())
